// Generates the lazy chunk's body.
//
// Why generated: the failure window in #3184 is the time the PAGE thread spends
// inside `LynxViewInstance.queryComponent`'s continuation —
// `await mtsRealm.loadScript(rootUrl)` (a blob <script> load into the main-thread
// realm iframe) followed by `processEvalResult(...)`, which is what actually
// invokes the chunk wrapper and registers its snapshot creators. That await
// yields to the event loop, so a background-thread patch message can be
// processed in front of it.
//
// The width of that window scales with how much code the main-thread realm has
// to load, parse and execute — so a REALISTICALLY SIZED lazy chunk (like a real
// product screen) reproduces where a toy chunk does not. Measured dose-response
// on one machine, 8 boots each (scripts/sweep-chunk-size.mjs):
//
//     rows |  lazy chunk | "Snapshot not found"
//      100 |    30.8 kB  |  0/8
//      300 |    87.6 kB  |  0/8
//      900 |     258 kB  |  0/8
//     2000 |     576 kB  |  1/8
//     4000 |    1172 kB  |  7/8
//     6000 |    1768 kB  |  8/8      <- the default
//
// (The row count is NOT the snapshot count — this JSX compiles to a couple of
// large static snapshots. What the knob actually controls is the byte size of
// the chunk's main-thread section, which is what the window's width tracks.)
//
// Usage: node scripts/gen-lazy-chunk.mjs [count]

import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outFile = path.join(here, "..", "src", "lazy-chunk-generated.tsx");
// 6000 rows => ~1.77 MB lazy chunk, comparable to the real app this was found
// in (1.64 MB) and past the threshold where the failure becomes deterministic.
const count = Number(process.argv[2] ?? 6000);

const blocks = [];
for (let i = 0; i < count; i++) {
  // Distinct source per element (the snapshot id hashes the module source), and
  // a distinct class so the CSS section is non-trivial too.
  blocks.push(
    `      <view className="row-${i}" style="padding:1px">`
      + `<text className="cell-${i}">cell ${i} — generated so the main-thread realm has real work to do</text>`
      + `</view>`,
  );
}

const source = `// GENERATED by scripts/gen-lazy-chunk.mjs — do not edit.
// ${count} rows.

export function GeneratedBody() {
  return (
    <view className="generated-body">
${blocks.join("\n")}
    </view>
  );
}
`;

mkdirSync(path.dirname(outFile), { recursive: true });
writeFileSync(outFile, source, "utf8");
console.log(
  `generated ${outFile} with ${count} rows (~${(source.length / 1024).toFixed(0)} KiB of source)`,
);
